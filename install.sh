#!/usr/bin/env bash
# One-command installer for Stay Woke.
#
#   git clone https://github.com/rjmorales13/staywoke.git && cd staywoke && ./install.sh
#
# Safe to re-run — every step is idempotent.
set -euo pipefail

BOLD=$'\033[1m'
GREEN=$'\033[0;32m'
CYAN=$'\033[0;36m'
YELLOW=$'\033[1;33m'
RED=$'\033[0;31m'
NC=$'\033[0m'
DIM=$'\033[2m'

step()  { printf " ${CYAN}⚙${NC}  ${BOLD}$1${NC}\n"; }
ok()    { printf " ${GREEN}✓${NC}  $1\n"; }
warn()  { printf " ${YELLOW}⚠${NC}  $1\n"; }
fail()  { printf " ${RED}✗${NC}  ${BOLD}$1${NC}\n" >&2; exit 1; }
detail(){ printf "     ${DIM}$1${NC}\n"; }

ORIGINAL_PATH="$PATH"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_SUPPORT_DIR="$HOME/Library/Application Support/6ix9ine"
VENV_DIR="$APP_SUPPORT_DIR/venv"
BIN_DIR="$HOME/.local/bin"

# ── header ──────────────────────────────────────────────────────────────

cat <<EOF

  ${BOLD}Stay Woke${NC} ${DIM}— keeps your Mac awake while agents work${NC}
  ${DIM}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}

EOF

# ── 1. Python ──────────────────────────────────────────────────────────

step "Finding Python 3.13+"

find_python313() {
  for candidate in python3.13 /opt/homebrew/bin/python3.13 /usr/local/bin/python3.13; do
    if command -v "$candidate" >/dev/null 2>&1; then
      command -v "$candidate"
      return 0
    fi
  done
  return 1
}

PYTHON313="$(find_python313)" || fail "Python 3.13+ not found.\n     Install it first: ${BOLD}brew install python@3.13${NC}"
PYVER="$("$PYTHON313" --version 2>&1)"
detail "$PYVER · $PYTHON313"
ok "$PYVER"

# ── 2. Runtime directory ───────────────────────────────────────────────

step "Preparing runtime directory"
mkdir -p "$APP_SUPPORT_DIR"
ok "$APP_SUPPORT_DIR"

# ── 3. Virtualenv ──────────────────────────────────────────────────────

step "Creating virtualenv"
if [ ! -x "$VENV_DIR/bin/python3" ]; then
  "$PYTHON313" -m venv "$VENV_DIR"
  ok "virtualenv created at $VENV_DIR"
else
  detail "already exists, reusing"
  ok "virtualenv ready"
fi

# ── 4. Dependencies ────────────────────────────────────────────────────

step "Installing Python dependencies"
"$VENV_DIR/bin/pip" install --quiet --upgrade pip
"$VENV_DIR/bin/pip" install --quiet -r "$REPO_ROOT/requirements.txt"
ok "dependencies installed"

# ── Command and helper ───────────────────────────────────────────────────

step "Installing staywoke → $BIN_DIR"
mkdir -p "$BIN_DIR"
write_wrapper() {
  printf '#!/bin/sh\nexec "%s/bin/python3" "%s/bin/%s.py" "$@"\n' "$VENV_DIR" "$REPO_ROOT" "$1"
}
wrapper="$(mktemp "$BIN_DIR/.staywoke.XXXXXX")"
trap 'rm -f "$wrapper"' EXIT
write_wrapper cli > "$wrapper"
chmod 755 "$wrapper"
mv -f "$wrapper" "$BIN_DIR/staywoke"
export PATH="$BIN_DIR:$PATH"

step "Setting up privileged helper"
"$BIN_DIR/staywoke" setup-privileged-helper
ok "privileged helper ready"

# ── Hooks ──────────────────────────────────────────────────────────────

step "Installing agent hooks"
HOOK_OUTPUT="$("$BIN_DIR/staywoke" install-hooks --all)" || true
printf '%s\n' "$HOOK_OUTPUT" | "$PYTHON313" -c '
import json, sys
failed = json.load(sys.stdin).get("failed", {})
for agent in ("claude", "opencode", "codex"):
    if agent in failed:
        sys.exit(f"{agent} hook setup failed: {failed[agent]}")
'
INSTALLED="$(echo "$HOOK_OUTPUT" | python3 -c "import sys,json; d=json.load(sys.stdin); print(' '.join(d.get('installed',[])))" 2>/dev/null || true)"
if [ -n "$INSTALLED" ]; then
  detail "hooks installed for: $INSTALLED"
fi
SKIPPED="$(echo "$HOOK_OUTPUT" | python3 -c "import sys,json; d=json.load(sys.stdin); print(' '.join(d.get('skipped',[])))" 2>/dev/null || true)"
FAILED_ITEMS="$(echo "$HOOK_OUTPUT" | python3 -c "
import sys, json
d = json.load(sys.stdin)
for k, v in d.get('failed', {}).items():
    # shorten the pending-research message
    print(k.replace('antigravity', 'Antigravity CLI'))
" 2>/dev/null || true)"
if [ -n "$FAILED_ITEMS" ]; then
  while IFS= read -r line; do
    detail "$line — hook integration pending research"
  done <<< "$FAILED_ITEMS"
fi
ok "hooks configured"

# ── Daemon ─────────────────────────────────────────────────────────────

step "Restarting background daemon"
"$BIN_DIR/staywoke" daemon-restart
ok "daemon running"

# Remove wrappers generated by earlier runs of this checkout only.
for name in 6ix9ine t69; do
  entry=cli
  if [ "$name" = t69 ]; then entry=tui; fi
  legacy="$BIN_DIR/$name"
  if [ -f "$legacy" ] && [ ! -L "$legacy" ] && write_wrapper "$entry" | cmp -s - "$legacy"; then
    rm -f "$legacy"
  fi
done

# ── PATH reminder ──────────────────────────────────────────────────────

PATH_MSG=""
case ":$ORIGINAL_PATH:" in
  *":$BIN_DIR:"*) ;;
  *)
    PATH_MSG="yes"
    warn "$BIN_DIR not on PATH"
    detail "Add this to your shell profile:"
    detail "  ${BOLD}export PATH=\"$BIN_DIR:\$PATH\"${NC}"
    ;;
esac

# ── Done ───────────────────────────────────────────────────────────────

echo ""
printf " ${GREEN}✓${NC}  ${BOLD}Stay Woke installed and running${NC}\n\n"

# ── Launch dashboard ───────────────────────────────────────────────────

if [ -x "$BIN_DIR/staywoke" ]; then
  # Write a .command file and open it — guaranteed new Terminal window.
  LAUNCHER="$APP_SUPPORT_DIR/launch-staywoke.command"
  cat > "$LAUNCHER" <<EOF
#!/bin/sh
exec "$BIN_DIR/staywoke"
EOF
  chmod +x "$LAUNCHER"
  # Save install window, open launcher, close install window.
  WIN_ID=$(osascript -e 'tell application "Terminal" to get id of front window' 2>/dev/null)
  open "$LAUNCHER"
  if [ -n "$WIN_ID" ]; then
    sleep 0.5
    osascript -e "tell application \"Terminal\" to close (every window whose id is $WIN_ID)" >/dev/null 2>&1
  fi
fi

exit 0
